"""The final-run plan of one dataset, written from its tuning studies (METHODS 5.5).

The plan lists its runs in the order they are trained:

1. the time-to-target group of METHODS 9.4: SASRec with its four objectives on leave-one-out,
   seeds 1 to 5, seeds as rounds and the four arms in a random order within each seed;
2. every other run with seeds 1 to 5, in a random order that interleaves arms and seeds:
   BERT4Rec on leave-one-out, all five arms on the temporal split, the shuffle controls of
   METHODS 3.3 and the floor baselines;
3. the seeds METHODS 7.5 adds, 6 to n, on leave-one-out and for the shuffle controls.

The orders are drawn from generators seeded by the dataset's name, so the plan with n seeds
starts with the plan with 5: adding seeds leaves the runs already trained as they are.
"""

from __future__ import annotations

import json
import random

from seqrec.analysis.power import N_RANGE, NEURAL_ARMS
from seqrec.runner.config import FLOOR_ARMS, START_LIMIT, default_limits

H2A_ARMS = ("sasrec-bce", "sasrec-ce", "sasrec-ss", "gsasrec")
H2A_SEEDS = range(1, 6)
SHUFFLE_CONTROL = {  # METHODS 3.3
    "sasrec-ce": ("ml-1m", "ml-20m", "steam", "video-games"),
    "bert4rec": ("ml-1m", "ml-20m"),
}
DOUBLING_SHARE = 0.2  # METHODS 5.2: more than this share of truncated trials doubles the limits
GUARD_HOURS = 8.0


def _study(rows: list[dict], dataset: str, tuning_batch: str, arm: str) -> tuple[dict, bool]:
    """The best parameters of an arm's study and whether its final runs double their limits."""
    found = [
        r for r in rows
        if (r["batch"], r["dataset"], r["arm"]) == (tuning_batch, dataset, arm)
    ]  # fmt: skip
    if len(found) != 1:
        raise ValueError(f"{arm} on {dataset}: {len(found)} studies in batch {tuning_batch}")
    params, share = found[0]["best_params"], found[0]["truncated_share"]
    if params in ("", None) or share in ("", None):
        raise ValueError(f"{arm} on {dataset}: the study has no best trial or no stopped trial")
    return json.loads(params), float(share) > DOUBLING_SHARE


def _value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    return json.dumps(v) if isinstance(v, str) else repr(v)


def _entry(arm: str, split: str, shuffle: str, seed: int, params: dict, doubled: bool) -> str:
    fields = {"arm": arm, "seed": seed}
    if split != "loo":
        fields["split"] = split
    if shuffle != "none":
        fields["shuffle"] = shuffle
    if doubled:
        epochs, patience = default_limits(arm)
        fields |= {
            "max_epochs": 2 * epochs, "patience": 2 * patience,
            "start_limit": 2 * START_LIMIT, "guard_hours": 2 * GUARD_HOURS,
        }  # fmt: skip
    lines = [f"{k} = {_value(v)}" for k, v in fields.items()]
    if params:
        inline = ", ".join(f"{k} = {_value(v)}" for k, v in params.items())
        lines.append(f"params = {{ {inline} }}")
    return "[[runs]]\n" + "\n".join(lines) + "\n"


def final_plan(
    best_rows: list[dict], dataset: str, tuning_batch: str, seeds: int, batch: str
) -> str:
    """The text of the plan `batch` for `dataset` with `seeds` leave-one-out seeds, from the
    rows of tuning_best.csv that belong to `tuning_batch`."""
    if seeds not in N_RANGE:
        raise ValueError(f"seeds must be {N_RANGE[0]} to {N_RANGE[-1]} (METHODS 7.5)")
    studies = {arm: _study(best_rows, dataset, tuning_batch, arm) for arm in NEURAL_ARMS}
    controls = [arm for arm, datasets in SHUFFLE_CONTROL.items() if dataset in datasets]

    order = random.Random(f"{dataset}/h2a")
    group = [(arm, "loo", "none", s) for s in H2A_SEEDS for arm in order.sample(H2A_ARMS, 4)]
    rest = [(arm, "loo", "none", s) for arm in NEURAL_ARMS for s in H2A_SEEDS]
    rest = [r for r in rest if r not in group]
    rest += [(arm, "gts", "none", s) for arm in NEURAL_ARMS for s in H2A_SEEDS]
    rest += [(arm, "loo", "train_eval", s) for arm in controls for s in H2A_SEEDS]
    rest += [(arm, split, "none", 0) for arm in FLOOR_ARMS for split in ("loo", "gts")]
    random.Random(f"{dataset}/rest").shuffle(rest)
    added = range(H2A_SEEDS[-1] + 1, seeds + 1)
    extra = [(arm, "loo", "none", s) for arm in NEURAL_ARMS for s in added]
    extra += [(arm, "loo", "train_eval", s) for arm in controls for s in added]
    random.Random(f"{dataset}/extra").shuffle(extra)

    head = (
        f"# Final runs on {dataset}, generated by `seqrec final-plan` from the studies of\n"
        f"# {tuning_batch} with {seeds} leave-one-out seeds (METHODS 5.5, 7.5). The first\n"
        f"# {len(group)} runs are the time-to-target group of METHODS 9.4, trained on one Pod.\n"
        f'batch = "{batch}"\nwarmup_s = 180\norder = "listed"\n\n'
        f'[defaults]\ndataset = "{dataset}"\nsplit = "loo"\nphase = "final"\n\n'
    )
    entries = [
        _entry(arm, split, shuffle, seed, *studies.get(arm, ({}, False)))
        for arm, split, shuffle, seed in group + rest + extra
    ]
    return head + "\n".join(entries)
